export interface EasebuzzInitiateResponse {
  orderId: string;
  txnid: string;
  amount: number;
  amountFormatted: string;
  currency: string;
  status: string;
  purpose: string;
  key: string;
  hash: string;
  accessKey: string | null;
  paymentUrl: string | null;
  isLiveGatewayAvailable: boolean;
  surl: string;
  furl: string;
  formData: {
    action: string;
    key: string;
    txnid: string;
    amount: string;
    productinfo: string;
    firstname: string;
    email: string;
    phone: string;
    hash: string;
    surl: string;
    furl: string;
    udf1: string;
    udf2: string;
    udf3: string;
    udf4: string;
    udf5: string;
  };
}

/**
 * Dispatches an Easebuzz transaction:
 * - If accessKey is generated by API, navigates to Easebuzz checkout URL.
 * - Otherwise creates an authoritative HTML Form POST to the Easebuzz gateway endpoint.
 */
export function openEasebuzzCheckout(data: EasebuzzInitiateResponse): void {
  if (typeof window === "undefined") return;

  if (data.paymentUrl && data.accessKey) {
    window.location.href = data.paymentUrl;
    return;
  }

  // Fallback / standard hosted portal form submission
  const form = document.createElement("form");
  form.method = "POST";
  form.action = data.formData.action;
  form.style.display = "none";

  Object.entries(data.formData).forEach(([key, val]) => {
    if (key === "action") return;
    const input = document.createElement("input");
    input.type = "hidden";
    input.name = key;
    input.value = String(val ?? "");
    form.appendChild(input);
  });

  document.body.appendChild(form);
  form.submit();
}

